// Generates the light ("chiaro") variant of the two Benessere Patrimoniale landings.
//
// The landings are authored dark-first with hard-coded colours. Rather than hand-maintaining a
// second stylesheet, this script reads each CSS module, maps every colour declaration to its
// light-palette counterpart (by property: a dark background becomes white/sand, light text on
// dark becomes ink, lime used as text or line becomes olive), and writes the result at the end
// of the same module between markers, scoped to `[data-theme="light"]` set by
// PatrimonialThemeFrame. Rerun after changing either module: `node scripts/build-patrimonial-light-theme.mjs`.
// Hand-tuned exceptions live in each module's "light theme: manual" block, which this script never touches.
import { readFileSync, writeFileSync } from 'node:fs';
import postcss from 'postcss';

const FILES = ['src/components/patrimonial-event.module.css', 'src/components/patrimonial-architect.module.css'];
const BEGIN = '/* === light theme: generated by scripts/build-patrimonial-light-theme.mjs — do not edit by hand === */';
const END = '/* === end light theme: generated === */';
const SCOPE = ':global([data-theme="light"])';
const MANUAL_BEGIN = '/* === light theme: manual === */';
const MANUAL_END = '/* === end light theme: manual === */';
const cut = (text, a, b) => { const i = text.indexOf(a); if (i === -1) return [text, '']; const j = text.indexOf(b, i) + b.length; return [text.slice(0, i) + text.slice(j), text.slice(i, j)]; };

// Components drawn over dark photographs (asset cards, labels on the 50/50 and coin images, the
// ticket over the hero photo) keep their original colours: they belong to the image, not to the page.
const KEEP_DARK = {
  'src/components/patrimonial-event.module.css': /\.(cta-ink|chip-ink|vAsset\w*|vBestTag|vHalf\w*|vInstImg|tile-d|coin-tag|s08[3-9])\b/,
  'src/components/patrimonial-architect.module.css': /\.(s117|s118)\b/,
};
const TEXT_PROPS = new Set(['color', 'caret-color', 'text-decoration-color', '-webkit-text-fill-color']);
const BG_PROPS = new Set(['background', 'background-color', 'background-image']);
const LINE_PROPS = /^(border(-top|-right|-bottom|-left)?(-color)?|outline(-color)?|fill|stroke|column-rule(-color)?)$/;
const SHADOW_PROPS = new Set(['box-shadow', 'text-shadow']);

const norm = v => v.toUpperCase();
// Dark-palette token -> light-palette token, per role.
const TEXT = { '#F7F4E8': '#07171D', 'VAR(--CREAM)': '#07171D', '#CDD6D4': '#41545A', 'VAR(--SOFT-DARK)': '#41545A', '#A3B1B0': '#5A6B70', 'VAR(--MUTED)': '#5A6B70', '#E1E7E5': '#26363C', '#D8FF42': '#5F7010', 'VAR(--LIME)': '#5F7010', '#E9FF8C': '#07171D', '#FF9D7A': '#9D4D34', 'VAR(--GOLD)': '#8A6A1F', 'VAR(--GOLD-SOFT)': '#7A5C17', '#D4AF63': '#8A6A1F', '#E6C98A': '#7A5C17', '#C9D3D1': '#41545A', '#8FA3A1': '#5A6B70' };
const BG = { '#07171D': '#FFFFFF', 'VAR(--INK)': '#FFFFFF', '#102229': '#EFEDE6', 'VAR(--INK-2)': '#EFEDE6', '#16303A': '#E4E2DA', 'VAR(--INK-3)': '#E4E2DA', '#040E12': '#EFEDE6', '#123239': '#EFEDE6', '#0F2A30': '#EFEDE6', 'VAR(--PETROL)': '#EFEDE6', '#FF9D7A': '#9D4D34' };
// Inside gradients (veils over photos) the dark ink fades into cream instead of white.
const BG_GRADIENT = { ...BG, '#07171D': '#F7F4E8', 'VAR(--INK)': '#F7F4E8' };
const LINE = { '#D8FF42': '#5F7010', 'VAR(--LIME)': '#5F7010', '#F7F4E8': '#07171D', 'VAR(--CREAM)': '#07171D', '#FF9D7A': '#9D4D34' };

const TOKEN = /#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b|var\(--[a-z0-9-]+\)|rgba?\(\s*\d+\s*,\s*\d+\s*,\s*\d+\s*(?:,\s*[\d.]+\s*)?\)/g;
const parseRgba = t => { const m = t.match(/rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)/); return m && { rgb: `${m[1]},${m[2]},${m[3]}`, a: m[4] === undefined ? 1 : Number(m[4]) }; };
const rgba = (rgb, a) => `rgba(${rgb},${+a.toFixed(3)})`;
const DARK_RGB = new Set(['7,23,29', '16,34,41', '4,14,18', '15,42,48']);
const CREAM_RGB = '247,244,232', LIME_RGB = '216,255,66', LOSS_RGB = '255,157,122', BLACK_RGB = '0,0,0';
const OLIVE_RGB = '95,112,16', INK_RGB = '7,23,29', RUST_RGB = '157,77,52', WHITE_RGB = '255,255,255';

function mapToken(role, token, value) {
  const c = parseRgba(token);
  if (!c) {
    const table = role === 'text' ? TEXT : role === 'bg' ? (/url\(|gradient/.test(value) ? BG_GRADIENT : BG) : role === 'line' ? LINE : {};
    return table[norm(token)] ?? token;
  }
  const { rgb, a } = c;
  if (rgb === LOSS_RGB) return rgba(RUST_RGB, a);
  if (role === 'bg') {
    // Dark veils over photos become cream veils; dark panels become white panels; faint ink tints on light stay.
    if (DARK_RGB.has(rgb)) return a >= 0.3 ? rgba(/url\(|gradient/.test(value) ? CREAM_RGB : WHITE_RGB, a) : token;
    if (rgb === CREAM_RGB) return a >= 0.5 ? rgba(WHITE_RGB, a) : rgba(INK_RGB, a);
    if (rgb === LIME_RGB) return a < 0.3 ? rgba(OLIVE_RGB, a) : token;
    return token;
  }
  if (role === 'line' || role === 'text') {
    if (rgb === CREAM_RGB) return rgba(INK_RGB, a);
    if (rgb === LIME_RGB) return rgba(OLIVE_RGB, a);
    if (rgb === '163,177,176') return rgba('90,107,112', a);
    return token;
  }
  if (role === 'shadow') {
    if (rgb === LIME_RGB) return rgba(OLIVE_RGB, a * 0.5);
    if (rgb === BLACK_RGB || DARK_RGB.has(rgb)) return rgba(INK_RGB, Math.min(a, 0.9) * 0.3);
    return token;
  }
  return token;
}

const roleOf = prop => TEXT_PROPS.has(prop) ? 'text' : BG_PROPS.has(prop) ? 'bg' : LINE_PROPS.test(prop) ? 'line' : SHADOW_PROPS.has(prop) ? 'shadow' : prop === 'accent-color' ? 'line' : null;

// A small dark element with lime text (ink pill, ink CTA, numbered dot) reads as an accent on a
// light page too, so it keeps its dark look.
function isDarkAccent(rule) {
  let darkBg = false, limeText = false;
  rule.walkDecls(d => {
    if (BG_PROPS.has(d.prop) && /^(#07171D|var\(--ink\))$/i.test(d.value.trim())) darkBg = true;
    if (d.prop === 'color' && /^(#D8FF42|var\(--lime\))$/i.test(d.value.trim())) limeText = true;
  });
  return darkBg && limeText;
}

function scopeSelector(sel) {
  return sel.split(',').map(s => `${SCOPE} ${s.trim()}`).join(',\n');
}

for (const file of FILES) {
  const [withoutGenerated] = cut(readFileSync(file, 'utf8'), BEGIN, END);
  const [base, manual] = cut(withoutGenerated, MANUAL_BEGIN, MANUAL_END);
  const root = postcss.parse(base, { from: file });
  const out = [];
  let count = 0;
  root.walkRules(rule => {
    if (rule.parent?.type === 'atrule' && /keyframes/i.test(rule.parent.name)) return;
    if (/:root|light theme: manual/.test(rule.selector)) return;
    if (rule.selector.includes('data-theme')) return; // manual light rules
    // Kept rules restate their original colours inside the scope, so broader light rules
    // (e.g. the generic link colour) can't override them by specificity.
    const keep = isDarkAccent(rule) || KEEP_DARK[file].test(rule.selector);
    const decls = [];
    rule.each(node => {
      if (node.type !== 'decl') return;
      const role = roleOf(node.prop);
      if (!role) return;
      const next = keep ? node.value : node.value.replace(TOKEN, t => mapToken(role, t, node.value));
      if (keep ? TOKEN.test(node.value) : next !== node.value) decls.push(`${node.prop}:${next}${node.important ? ' !important' : ''}`);
      TOKEN.lastIndex = 0;
    });
    if (!decls.length) return;
    count += decls.length;
    let css = `${scopeSelector(rule.selector)}{${decls.join(';')}}`;
    for (let p = rule.parent; p && p.type === 'atrule'; p = p.parent) css = `@${p.name} ${p.params}{${css}}`;
    out.push(css);
  });
  // Generated rules first, hand-tuned exceptions last so they win at equal specificity.
  const block = `\n\n${BEGIN}\n${out.join('\n')}\n${END}\n${manual ? `\n${manual}\n` : ''}`;
  writeFileSync(file, base.replace(/\s+$/, '') + block);
  console.log(`${file}: ${out.length} rules, ${count} declarations`);
}
